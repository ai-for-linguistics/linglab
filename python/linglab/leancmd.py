"""`linglab lean`: build the Lean workspace and turn theorems into `lean` entries.

Naming convention (SPEC section 5): in `namespace T_MK`, `theorem F01` proves the claim,
`theorem F01_fail` proves its negation. Combined with the fact's `expected`:
claim proved & expected holds -> pass; claim proved & expected fails -> fail;
negation proved & expected fails -> pass; negation proved & expected holds -> fail.
Namespace `Raw` (Raw.lean) maps to theory RAW: each listed claim is proved by membership -> pass.
"""
import glob
import os
import re
import shutil
import subprocess

from .common import load_project, write_json, today, sort_results, facts_of, drop_kind
from . import forbidden

NS = re.compile(r"^\s*namespace\s+(\S+)")
END = re.compile(r"^\s*end\s+(\S+)\s*$")
THM = re.compile(r"^\s*(?:theorem|lemma|example)\s+(F\d+[A-Za-z]*?)(_fail)?\b")
HINT = ("Lean/Lake not found. To use the Lean checks install elan "
        "(https://leanprover-community.github.io/get_started.html), then re-run `linglab lean`. "
        "Without Lean, the Python checks still work.")


def scan_theorems(root):
    """-> [(namespace, fact id, negated, relative file)]"""
    found = []
    for p in sorted(glob.glob(os.path.join(root, "lean", "**", "*.lean"), recursive=True)):
        if ".lake" in p.split(os.sep):
            continue
        ns = []
        for line in open(p, encoding="utf-8"):
            if line.lstrip().startswith("--"):
                continue
            m = NS.match(line)
            if m:
                ns.append(m.group(1))
                continue
            m = END.match(line)
            if m and ns and ns[-1] == m.group(1):
                ns.pop()
                continue
            m = THM.match(line)
            if m and ns:
                found.append((ns[-1], m.group(1), bool(m.group(2)), os.path.relpath(p, root)))
    return found


def init_lean(root=".", linglib=False):
    """Copy the toolkit's Lean workspace to <project>/lean/ (once). One workspace per project, never one per agent.
    With linglib=True, overlay the linglib mode (lakefile requiring linglib, linglib's Lean version, a worked adapter).
    Nothing is downloaded here: the user is asked first (see extras/linglib/README.md)."""
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "..", "..", "lean")
    dst = os.path.join(root, "lean")
    if os.path.exists(dst):
        print("lean/ already exists: nothing copied")
        return 0
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns(".lake", "build", "*.olean"))
    if linglib:
        over = os.path.join(here, "..", "..", "extras", "linglib")
        shutil.copytree(over, dst, dirs_exist_ok=True)
        if os.path.exists(os.path.join(dst, "lake-manifest.json")):
            os.remove(os.path.join(dst, "lake-manifest.json"))   # regenerated by `lake update`
        print("copied the Lean workspace to lean/ in LINGLIB MODE (not built, nothing downloaded).")
        print("Before going on, tell the user: the Lean version of this project becomes linglib's (see lean/lean-toolchain);")
        print("the first `cd lean && lake update && lake build` downloads linglib and Mathlib (about 2 GB, about 7 GB on disk, 5 to 20 minutes);")
        print("linglib is AI-assisted and may contain errors. Details: lean/README.md. A worked adapter is lean/Linglab/Theories/FoxIE.lean.")
        return 0
    print("copied the Lean workspace to lean/ (the interface; put your theories under lean/Linglab/Theories/, a worked example is in utils/example/lean/)")
    return 0


def _needs_fetch(lean_dir):
    """Linglib mode whose packages are not fetched yet."""
    lk = os.path.join(lean_dir, "lakefile.toml")
    if not os.path.exists(lk) or "linglib" not in open(lk, encoding="utf-8").read():
        return False
    return not os.path.isdir(os.path.join(lean_dir, ".lake", "packages", "linglib"))


def run_lean(root=".", build_only=False, out=print):
    lean_dir = os.path.join(root, "lean")
    if not os.path.isdir(lean_dir):
        out("no lean/ folder yet: run `python3 utils/bin/linglab.py lean --init` to create it")
        return 0
    if shutil.which("lake") is None:
        out(HINT)
        return 0
    if _needs_fetch(lean_dir):
        out("linglib mode: the packages are not fetched yet. Ask the user first (about 2 GB to download, about 7 GB on disk, "
            "5 to 20 minutes), then run `lake update` in lean/ and `linglab lean` again. See lean/README.md.")
        return 0
    r = subprocess.run(["lake", "build"], cwd=lean_dir, capture_output=True, text=True)
    log = r.stdout + r.stderr
    if r.returncode != 0:
        n = drop_kind(root, "lean")
        out("lake build failed:\n" + log[-4000:])
        out("%d stale lean entries removed from data/results.json" % n)
        return 1
    bad = forbidden.scan_lean(root)
    if re.search(r"declaration uses ['`]sorry['`]", log) and not any(b.endswith("sorry") for b in bad):
        bad.append("lake build: declaration uses 'sorry'")
    if bad:
        n = drop_kind(root, "lean")
        out("lake build ok, but the build is not a proof: sorry or added axioms found:")
        for b in bad:
            out("  " + b)
        out("no lean entries recorded; %d stale lean entries removed from data/results.json" % n)
        return 1
    out("lake build ok")
    if build_only:
        return 0
    d = load_project(root)
    norm = lambda s: s.replace("-", "_")
    theories = {norm(t["id"]): t["id"] for t in d["theories"]}
    theories["Raw"] = "RAW"
    facts = {f["id"]: f for f in facts_of(d["statements"])}
    new, seen = {}, {}
    for ns, fid, neg, rel in scan_theorems(root):
        tid, f = theories.get(ns.split(".")[-1]), facts.get(fid)
        if tid is None or f is None:
            continue
        exp = f.get("expected", "holds") == "holds"
        outcome = "pass" if tid == "RAW" else ("pass" if (exp != neg) else "fail")
        key = (fid, tid)
        if key in seen and seen[key] != (neg,):
            out("ERROR both %s and its negation are proved in %s" % (fid, tid))
            return 1
        seen[key] = (neg,)
        new[key] = {"fact": fid, "theory": tid, "outcome": outcome, "kind": "lean", "who": "lake",
                    "when": today(), "reasons": "theorem %s.%s%s builds" % (ns, fid, "_fail" if neg else ""),
                    "ref": rel, "bound": "", "outside_fragment": False, "depends_on": "", "note": ""}
    results = [e for e in d["results"] if not (e["kind"] == "lean" and e.get("who") == "lake")]
    results += new.values()
    write_json(os.path.join(root, "data", "results.json"),
               sort_results(results, d["statements"], d["theories"]))
    out("%d lean entries written" % len(new))
    return 0
